def normalize_language(code: str) -> str:
    """Maps any supported code (or unknown value) to a key in LANGUAGES."""
    code = (code or "").strip()
    return code if code in LANGUAGES else DEFAULT_LANGUAGE


def t(language: str, key: str, **kwargs) -> str:
    """Returns a canned reply in the requested language, formatted with kwargs."""
    strings = LANGUAGES[normalize_language(language)]
    return strings[key].format(**kwargs) if kwargs else strings[key]


def stt_language(language: str) -> str:
    """Prisma STT code: Hindi mode auto-detects Hindi/English so Hinglish works."""
    language = normalize_language(language)
    return "en-IN,hi-IN" if language == "hi-IN" else language
